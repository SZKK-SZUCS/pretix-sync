#!/usr/bin/env python3
"""
Translation build (no gettext tools needed).

  python tools/build-i18n.py

1. Scans the PHP sources for __() / _e() / esc_html__() / esc_attr__() / esc_html_e() calls with the 'pretix-sync'
   text domain and writes languages/pretix-sync.pot.
2. Compiles every languages/pretix-sync-*.po to a .mo file.
3. Reports strings that are in the .pot but missing from a .po (and the other way round), and exits 1 if any are
   missing, so a release does not ship an untranslated string by accident.

Only simple entries (msgid / msgstr, no plurals or contexts) are supported, which is all the plugin uses.
"""
import glob
import os
import re
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOMAIN = 'pretix-sync'
CALL = re.compile(
    r"\b(?:__|_e|esc_html__|esc_attr__|esc_html_e)\(\s*"
    r"(?:'((?:[^'\\]|\\.)*)'|\"((?:[^\"\\]|\\.)*)\")\s*,\s*'" + DOMAIN + r"'\s*\)",
    re.S,
)


def php_unescape(single, double):
    if single is not None:
        return single.replace("\\'", "'").replace('\\\\', '\\')
    s = double
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c == '\\' and i + 1 < len(s):
            n = s[i + 1]
            out.append({'n': '\n', 't': '\t', '"': '"', '\\': '\\', '$': '$'}.get(n, '\\' + n))
            i += 2
        else:
            out.append(c)
            i += 1
    return ''.join(out)


def po_quote(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\t', '\\t') + '"'


def po_unquote(s):
    s = s.strip()[1:-1]
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c == '\\' and i + 1 < len(s):
            n = s[i + 1]
            out.append({'n': '\n', 't': '\t', '"': '"', '\\': '\\'}.get(n, n))
            i += 2
        else:
            out.append(c)
            i += 1
    return ''.join(out)


def extract():
    found = {}
    files = [os.path.join(ROOT, 'pretix-sync.php')] + sorted(glob.glob(os.path.join(ROOT, 'includes', '*.php')))
    for path in files:
        src = open(path, encoding='utf-8').read()
        for m in CALL.finditer(src):
            msgid = php_unescape(m.group(1), m.group(2))
            line = src.count('\n', 0, m.start()) + 1
            found.setdefault(msgid, []).append('%s:%d' % (os.path.relpath(path, ROOT).replace('\\', '/'), line))
    return found


def write_pot(found):
    lines = [
        '# Pretix Sync translation template. Generated by tools/build-i18n.py - do not edit.',
        'msgid ""', 'msgstr ""',
        '"Project-Id-Version: Pretix Sync\\n"',
        '"MIME-Version: 1.0\\n"',
        '"Content-Type: text/plain; charset=UTF-8\\n"',
        '"Content-Transfer-Encoding: 8bit\\n"',
        '',
    ]
    for msgid in sorted(found):
        lines.append('#: ' + ' '.join(found[msgid]))
        lines.append('msgid ' + po_quote(msgid))
        lines.append('msgstr ""')
        lines.append('')
    open(os.path.join(ROOT, 'languages', DOMAIN + '.pot'), 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))


def read_po(path):
    entries, cur, key = {}, {'id': None, 'str': None}, None
    header = ''
    for raw in open(path, encoding='utf-8').read().split('\n') + ['']:
        line = raw.strip()
        if line.startswith('msgid '):
            if cur['id'] is not None and cur['str'] is not None:
                entries[cur['id']] = cur['str']
            cur, key = {'id': po_unquote(line[6:]), 'str': None}, 'id'
        elif line.startswith('msgstr '):
            cur['str'], key = po_unquote(line[7:]), 'str'
        elif line.startswith('"') and key:
            cur[key] += po_unquote(line)
        elif line == '' and key:
            if cur['id'] is not None and cur['str'] is not None:
                entries[cur['id']] = cur['str']
            cur, key = {'id': None, 'str': None}, None
    return entries


def write_mo(entries, path):
    items = sorted((k, v) for k, v in entries.items() if v != '' or k == '')
    ids, strs = b'', b''
    offsets = []
    for k, v in items:
        kb, vb = k.encode('utf-8'), v.encode('utf-8')
        offsets.append((len(ids), len(kb), len(strs), len(vb)))
        ids += kb + b'\0'
        strs += vb + b'\0'
    n = len(items)
    keystart = 7 * 4 + 16 * n
    valuestart = keystart + len(ids)
    out = struct.pack('Iiiiiii', 0x950412DE, 0, n, 7 * 4, 7 * 4 + n * 8, 0, 0)
    out += b''.join(struct.pack('ii', o[1], keystart + o[0]) for o in offsets)
    out += b''.join(struct.pack('ii', o[3], valuestart + o[2]) for o in offsets)
    open(path, 'wb').write(out + ids + strs)


def main():
    os.makedirs(os.path.join(ROOT, 'languages'), exist_ok=True)
    found = extract()
    write_pot(found)
    print('pot: %d strings' % len(found))
    bad = 0
    for po in sorted(glob.glob(os.path.join(ROOT, 'languages', DOMAIN + '-*.po'))):
        entries = read_po(po)
        missing = [k for k in found if not entries.get(k)]
        stale = [k for k in entries if k and k not in found]
        for k in missing:
            print('MISSING in %s: %r' % (os.path.basename(po), k[:80]))
        for k in stale:
            print('stale in %s: %r' % (os.path.basename(po), k[:80]))
        write_mo(entries, po[:-3] + '.mo')
        print('%s: %d translated, %d missing, %d stale' % (os.path.basename(po), len(found) - len(missing), len(missing), len(stale)))
        bad += len(missing)
    sys.exit(1 if bad else 0)


if __name__ == '__main__':
    main()
